import * as fs from "fs";
import path from "path";
import chalk from "chalk"; // You may need to install this package



function get_plugins(): string[] {
    // scan the node_modules directory for all the installed plugins
    // a package is a module if it has a "ormi_plugin" field in its package.json

    // get the list of all the directories in the node_modules directory
    const node_modules = path.join(process.cwd(), "node_modules");
    if (!fs.existsSync(node_modules)) {
        console.log(chalk.red("✗ No node_modules directory found."));
        return [];
    }

    console.log(chalk.cyan("🔍 Scanning node_modules directory for ORMI plugins..."));
    
    const dirs = fs.readdirSync(node_modules, { withFileTypes: true })
        .filter(dirent => {
            try {
                const fullPath = path.join(node_modules, dirent.name);
                // Check if it's a directory or a symlink that points to a directory
                return dirent.isDirectory() || 
                       (dirent.isSymbolicLink() && fs.statSync(fullPath).isDirectory());
            } catch (err) {
                // console.log(`Error checking ${dirent.name}: ${err.message}`);
                return false;
            }
        })
        .map(dirent => dirent.name);

    // get the list of all the directories that are ORMI plugins
    let scannedCount = 0;
    const totalDirs = dirs.length;
    
    console.log(chalk.yellow(`📦 Found ${totalDirs} potential packages to check`));
    
    const plugins = dirs.filter(dir => {
        const dirPath = path.join(node_modules, dir);
        const package_json = path.join(dirPath, "package.json");
        if (!fs.existsSync(package_json)) {
            // Skip silently
            return false;
        }

        // Show progress periodically
        scannedCount++;
        if (scannedCount % 50 === 0 || scannedCount === totalDirs) {
            process.stdout.write(`\r${chalk.blue('⏳')} Scanning packages: ${chalk.green(scannedCount)}/${chalk.green(totalDirs)} [${Math.round((scannedCount/totalDirs)*100)}%]`);
        }
        
        try {
            const pckg = JSON.parse(fs.readFileSync(package_json, "utf-8"));
            if (pckg["ormi_plugin"] !== undefined) {
                // process.stdout.write(`\n${chalk.green('✓')} Found ORMI plugin: ${chalk.bold(dir)}`);
                return true;
            }
            return false;
        } catch (err) {
            // Silent error handling
            return false;
        }
    });

    process.stdout.write(`\r${chalk.blue('⏳')} Scanning packages: ${chalk.green(totalDirs)}/${chalk.green(totalDirs)} [${100}%]`)

    // Add a newline after progress output
    if (totalDirs > 0) {
        console.log("\n");
    }
    
    return plugins;
}


function save_source_file(source:string,path:string){
    const source_file = path;
    try {
        fs.writeFileSync(source_file, source);
        console.log(chalk.green('💾 Source file saved successfully!'));
    } catch (err) {
        console.error(chalk.red(`🚨 Error saving source file: ${(err as any).message}`));
    }
}

function generate_source_file(plugins: string[]):string{

    /*
        "use client"

        import { PluginRegistry } from "ormi-core/plugins";


        const registry : PluginRegistry = {
            "ormi-standard-widgets": import("ormi-standart-widgets") as any,
            "ormi-ros-2": import("ormi-ros-2") as any,
            "ormi-random": import("ormi-random") as any,
            "ormi-fligth-indicator" : import("ormi-fligth-indicator") as any,
        }

        export default registry;
    */

    let source = "/* eslint-disable @typescript-eslint/no-explicit-any */\n";
    source += `"use client"\n\n`;
    source += `// This file is auto-generated by the ORMI CLI\n\n`;
    source += `import { PluginRegistry } from "ormi-core/plugins";\n\n`;
    source += `const registry : PluginRegistry = {\n`;
    plugins.forEach(plugin => {
        source += `    "${plugin}": import("${plugin}") as any,\n`;
    });
    source += `}\n\n`;
    source += `export default registry;`;

    return source;
}

export async function init(path: string) {
    console.log(chalk.magenta('🚀 Initializing ORMI Core...'));
    
    const startTime = Date.now();
    const plugins = get_plugins();
    const endTime = Date.now();
    
    console.log(chalk.green(`\n✨ Found ${plugins.length} ORMI plugins in ${((endTime - startTime)/1000).toFixed(2)}s`));
    
    if (plugins.length > 0) {
        console.log(chalk.yellow('📋 Discovered plugins:'));
        plugins.forEach((plugin, index) => {
            console.log(chalk.cyan(`  ${index + 1}. ${plugin}`));
        });
    } else {
        console.log(chalk.yellow('⚠️  No ORMI plugins found. You can install plugins to extend functionality.'));
    }

    console.log(chalk.magenta('\n📝 Generating source file...'));
    const source = generate_source_file(plugins);

    console.log(chalk.magenta('💾 Saving source file...'))
    save_source_file(source,path);

}

